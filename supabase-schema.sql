create table if not exists public.perfiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nombre text not null default '',
  correo text not null default '',
  rol text not null default 'estudiante',
  telefono text not null default '',
  direccion text not null default '',
  institucion text not null default '',
  departamento text not null default '',
  updated_at timestamptz not null default now()
);

alter table public.perfiles
add column if not exists rol text not null default 'estudiante';

do $$
begin
  alter table public.perfiles
  add constraint perfiles_rol_check
  check (rol in ('estudiante', 'profesor', 'directivo', 'padre'));
exception
  when duplicate_object then null;
end $$;

create or replace function public.crear_perfil_nuevo_usuario()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.perfiles (id, nombre, correo, rol)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    coalesce(new.email, ''),
    'estudiante'
  )
  on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists al_crear_usuario on auth.users;
create trigger al_crear_usuario
after insert on auth.users
for each row execute function public.crear_perfil_nuevo_usuario();

create or replace function public.proteger_rol_propio()
returns trigger
language plpgsql
as $$
begin
  if old.rol is distinct from new.rol and auth.uid() = old.id then
    raise exception 'El usuario no puede cambiar su propio rol';
  end if;

  return new;
end;
$$;

drop trigger if exists proteger_rol_propio on public.perfiles;
create trigger proteger_rol_propio
before update on public.perfiles
for each row execute function public.proteger_rol_propio();

create table if not exists public.registros_horas (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references auth.users(id) on delete cascade,
  fecha date not null,
  hora_inicio time not null,
  hora_termino time not null,
  actividades text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.evidencias (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references auth.users(id) on delete cascade,
  nombre_archivo text not null,
  descripcion text not null,
  url_archivo text not null,
  estado text not null default 'Pendiente',
  created_at timestamptz not null default now()
);

insert into storage.buckets (id, name, public)
values ('evidencias', 'evidencias', true)
on conflict (id) do nothing;

alter table public.perfiles enable row level security;
alter table public.registros_horas enable row level security;
alter table public.evidencias enable row level security;

drop policy if exists "Cada usuario puede consultar su perfil" on public.perfiles;
drop policy if exists "Cada usuario puede crear su perfil" on public.perfiles;
drop policy if exists "Cada usuario puede actualizar su perfil" on public.perfiles;
drop policy if exists "Cada usuario puede consultar sus registros" on public.registros_horas;
drop policy if exists "Cada usuario puede crear sus registros" on public.registros_horas;
drop policy if exists "Cada usuario puede consultar sus evidencias" on public.evidencias;
drop policy if exists "Cada usuario puede crear sus evidencias" on public.evidencias;
drop policy if exists "Cada usuario puede subir sus archivos" on storage.objects;
drop policy if exists "Usuarios autenticados pueden subir evidencias" on storage.objects;
drop policy if exists "Cualquiera puede leer los archivos de evidencias" on storage.objects;
drop policy if exists "Todos pueden leer evidencias" on storage.objects;

create policy "Cada usuario puede consultar su perfil"
  on public.perfiles for select using (auth.uid() = id);
create policy "Cada usuario puede crear su perfil"
  on public.perfiles for insert with check (auth.uid() = id);
create policy "Cada usuario puede actualizar su perfil"
  on public.perfiles for update using (auth.uid() = id) with check (auth.uid() = id);

create policy "Cada usuario puede consultar sus registros"
  on public.registros_horas for select using (auth.uid() = usuario_id);
create policy "Cada usuario puede crear sus registros"
  on public.registros_horas for insert with check (auth.uid() = usuario_id);

create policy "Cada usuario puede consultar sus evidencias"
  on public.evidencias for select using (auth.uid() = usuario_id);
create policy "Cada usuario puede crear sus evidencias"
  on public.evidencias for insert with check (auth.uid() = usuario_id);

create policy "Usuarios autenticados pueden subir evidencias"
  on storage.objects for insert with check (
    bucket_id = 'evidencias'
    and auth.uid() is not null
    and split_part(name, '/', 1) = auth.uid()::text
  );

create policy "Todos pueden leer evidencias"
  on storage.objects for select using (bucket_id = 'evidencias');